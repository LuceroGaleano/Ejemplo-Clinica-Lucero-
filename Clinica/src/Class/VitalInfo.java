
package Class;


public class VitalInfo {
    protected String bloodPresure;
    protected String temperature;
    protected String pulse;
    protected String oxygen;

    public VitalInfo(String bloodPresure, String temperature, String pulse, String oxygen) {
        this.bloodPresure = bloodPresure;
        this.temperature = temperature;
        this.pulse = pulse;
        this.oxygen = oxygen;
    }
}
